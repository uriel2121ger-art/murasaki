#pragma once

// A profile: a named set of desktop pets with all their fields (docs/pets/automation.md, "Profiles"). It holds the pets only: no wallpaper, no setting, nothing of the
// session (hidden, arranging, muted).

#include "automation.h"
#include "petstore.h"

#include <QJsonObject>
#include <QList>
#include <QString>

#include <optional>

namespace murasaki {

// One pet of a profile: the placement without its petId, and a small number that names the entry across switches (a timeline names the pet by it).
struct ProfileEntry {
    int slot = 0;
    PetPlacement pet;

    QJsonObject toJson() const;
    bool operator==(const ProfileEntry &other) const = default;
};

struct Profile {
    QString id; // uuid, generated by the store
    QString name;
    QList<ProfileEntry> pets;
    QString origin;

    QJsonObject toJson() const;
    bool operator==(const Profile &other) const = default;
};

bool validateProfile(const Profile &profile, QString *error = nullptr);

// Applies the keys of changes (name, pets, origin) onto base and validates the result. "pets" is an array of entries (a placement as ListPets gives it, without petId
// or with it: it is ignored, plus a "slot"; a missing slot is the next free one). Unknown keys are ignored; a known key of the wrong type is an error naming it.
std::optional<Profile> applyProfileChanges(const Profile &base, const QJsonObject &changes, QString *error = nullptr);

// The profile the pets make: slots 0, 1, 2... in the order of the list, petIds dropped.
QList<ProfileEntry> entriesFromPets(const QList<PetPlacement> &pets);

} // namespace murasaki
