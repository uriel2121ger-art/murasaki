#pragma once

// A trigger: a source (something that happens) and one action (what the pets do about it). Both lists are closed (docs/pets/automation.md): no source reads the
// screen, the keyboard or the microphone, and no action runs a program, opens a file or a web address (tst_automationclosed pins both lists).

#include <QJsonObject>
#include <QList>
#include <QString>

#include <optional>

namespace murasaki {

enum class TriggerKind { AppFocus, AppOpen, Fullscreen, Time, Interval, Idle, Power, Session, Game, Output, Shortcut, SignalFile, Fire, DBus, Screen };

QString triggerKindName(TriggerKind kind); // "app-focus", "app-open", "fullscreen", "time", "interval", "idle", "power", "session", "game", "output", "shortcut", "signal-file", "fire", "dbus", "screen"
std::optional<TriggerKind> triggerKindFromName(const QString &name);
QList<TriggerKind> allTriggerKinds();

struct TriggerSource {
    TriggerKind kind = TriggerKind::Fire;
    QString app;            // app-focus, app-open, fullscreen: a window class, `*` and `?` match as in the pause rules
    bool onLeave = false;   // app-focus, app-open, fullscreen: fire when it stops (the window loses the focus, the last one closes, the fullscreen ends)
    QString output;         // fullscreen
    QString at;             // time: "HH:MM" local
    QList<int> days;        // time: 0 (Sunday) to 6 (Saturday); empty: every day
    int minutes = 0;        // interval (everyMinutes), idle
    QString state;          // power: battery|ac; session: locked|unlocked; game: started|ended; output: added|removed
    QString name;           // signal-file, fire: the name; output: the connector (empty: any)
    QString id;             // shortcut
    QString description;    // shortcut: what the desktop's dialog shows
    QString interface;      // dbus
    QString member;         // dbus
    QString senderNamespace; // dbus
    QJsonObject screen;     // screen: kept as imported, never used

    QJsonObject toJson() const;
    bool operator==(const TriggerSource &other) const = default;
};

enum class TriggerActionType { Timeline, Scene, Profile, HideAll, ShowAll, ToggleHidden, StopSounds, Mute, PlaySound };

QString triggerActionName(TriggerActionType type); // "timeline", "scene", "profile", "hide-all", "show-all", "toggle-hidden", "stop-sounds", "mute", "play-sound"
std::optional<TriggerActionType> triggerActionFromName(const QString &name);
QList<TriggerActionType> allTriggerActionTypes();

struct TriggerAction {
    TriggerActionType type = TriggerActionType::HideAll;
    QString id;      // timeline, profile
    QString item;    // scene (the item whose pets play it; empty: the pet is named by petId), play-sound
    QString petId;   // scene, play-sound
    int index = 0;   // scene
    QString mute;    // mute: on|off|toggle

    QJsonObject toJson() const;
    bool operator==(const TriggerAction &other) const = default;
};

struct Trigger {
    QString id; // uuid, generated by the store
    QString name;
    bool enabled = true;
    int cooldownMs = 500;
    bool hold = false; // shortcut: the action runs on press and its inverse on release
    TriggerSource source;
    TriggerAction action;
    QString origin; // where it came from ("package X"); empty for a trigger the user made

    QJsonObject toJson() const;
    bool operator==(const Trigger &other) const = default;
};

bool validateName(const QString &name, QString *error); // for the names of signal files, fires and shortcut ids: [A-Za-z0-9._-]{1,64}
bool validateTrigger(const Trigger &trigger, QString *error = nullptr);
// The action that undoes `action` for a hold shortcut (hide-all <-> show-all, toggle with toggle, mute on <-> off, a timeline is stopped), or nothing when it has none.
std::optional<TriggerAction> inverseAction(const TriggerAction &action);

// Applies the keys of changes (name, enabled, cooldownMs, mode, source, action, origin) onto base and validates the result. Unknown keys are ignored; a known key of the
// wrong type is an error naming it. id can not be changed.
std::optional<Trigger> applyTriggerChanges(const Trigger &base, const QJsonObject &changes, QString *error = nullptr);

// Whether `text` matches the pattern (`*` any run, `?` one character; case-insensitive), as the pause rules do.
bool matchesApplication(const QString &pattern, const QString &text);

} // namespace murasaki
