#pragma once

// A timeline: tracks that each drive one pet with a list of actions (docs/pets/automation.md, "Timelines"). The list of action kinds is closed: none of them runs
// a program, opens a file or a web address (tst_automationclosed pins it).

#include "petstates.h"

#include <QJsonObject>
#include <QList>
#include <QString>

#include <optional>

namespace murasaki {

enum class ActionKind { Place, Show, Hide, Move, Sound, Wait, StopSounds, Track };

// The names of the kinds, in the order of the enum: "place", "show", "hide", "move", "sound", "wait", "stopSounds", "track".
QString actionKindName(ActionKind kind);
std::optional<ActionKind> actionKindFromName(const QString &name);
QList<ActionKind> allActionKinds();

struct TimelineAction {
    ActionKind kind = ActionKind::Wait;
    double x = 0;           // place, move
    double y = 0;           // place, move
    QString output;         // place: the output the position is relative to (empty: the pet's own)
    bool centre = false;    // place, move: x and y are where the CENTRE of the pet goes (anchor "centre", as Anima's packs say); false: its top-left corner
    QString variant;        // show: the animation to show (empty: the pet's own)
    bool smooth = false;    // move: false teleports, true takes durationMs
    int durationMs = 0;     // move
    int waitMs = 0;         // wait
    PetTrackingMode tracking = PetTrackingMode::Off; // track: the mouse tracking the pet has while the run lasts (the runtime layer, never stored)

    QJsonObject toJson() const;
    bool operator==(const TimelineAction &other) const = default;
};

// The pet a track drives: exactly one of the three ways to name it.
struct PetRef {
    QString petId;  // a pet that exists
    QString item;   // the first pet of the item, or one made for the run when there is none (ephemeral)
    QString variant; // with item: the variant of the made pet (empty: the item's first)
    int slot = -1;  // inside a profile run: the entry's slot

    QJsonObject toJson() const;
    bool operator==(const PetRef &other) const = default;
};

struct TimelineTrack {
    PetRef pet;
    bool startVisible = true; // false: the pet is hidden when the run starts
    QList<TimelineAction> actions;

    bool operator==(const TimelineTrack &other) const = default;
};

struct Timeline {
    QString id;   // uuid, generated by the store
    QString name;
    double speed = 1;   // divides every wait and move (kMinTimelineSpeed..kMaxTimelineSpeed)
    bool restore = true; // the touched pets go back to their stored state at the end
    QList<TimelineTrack> tracks;
    QString origin;     // where it came from ("package X"); empty for a timeline the user made

    // The longest track's length at speed 1 (waits and smooth moves), in ms.
    qint64 lengthMs() const;
    QJsonObject toJson() const;
    bool operator==(const Timeline &other) const = default;
};

bool validateAction(const TimelineAction &action, QString *error = nullptr);
bool validateTimeline(const Timeline &timeline, QString *error = nullptr);

// Applies the keys of changes (name, speed, restore, tracks, origin) onto base and validates the result. Unknown keys are ignored; a known key of the wrong type is an
// error naming it (a bad action names its track and index). id can not be changed.
std::optional<Timeline> applyTimelineChanges(const Timeline &base, const QJsonObject &changes, QString *error = nullptr);

} // namespace murasaki
