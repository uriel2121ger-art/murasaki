#!/usr/bin/env python3
"""Golden values for the motion curve evaluator (src/puppet/motion.cpp), computed independently of it.

The curves are written the way a *.motion3.json writes them (docs/pets/puppets.md, section 3.2): one flat list holding a first point, then for each segment its code (0 linear,
1 cubic Bezier, 2 stepped, 3 inverse stepped) and its points. Values are found with exact rational arithmetic: linear by the line through the end points, the two steps by their
definition, and a Bezier by solving the cubic that gives time from the parameter with 90 bisections in rational numbers (a different method from the C++ evaluator's floating point).

  puppet_curves.py --out tests/puppetcurvegolden.h     write the header the test includes
  puppet_curves.py --check tests/puppetcurvegolden.h   fail (exit 1) if the header differs from what this script computes
"""
import argparse
import random
import sys
from fractions import Fraction as F


def parse(flat):
    """flat list -> list of segments (kind, [points]), first point"""
    first = (F(flat[0]), F(flat[1]))
    segs = []
    prev = first
    i = 2
    while i < len(flat):
        kind = int(flat[i])
        i += 1
        n = 3 if kind == 1 else 1
        pts = [prev]
        for _ in range(n):
            pts.append((F(flat[i]), F(flat[i + 1])))
            i += 2
        segs.append((kind, pts))
        prev = pts[-1]
    return first, segs


def bez(a, b, c, d, s):
    u = 1 - s
    return u * u * u * a + 3 * u * u * s * b + 3 * u * s * s * c + s * s * s * d


def value(flat, t):
    t = F(t)
    first, segs = parse(flat)
    if not segs or t <= first[0]:
        return first[1]
    last = segs[-1][1][-1]
    if t >= last[0]:
        return last[1]
    chosen = None
    for kind, pts in segs:  # the last segment starting at or before t
        if pts[0][0] <= t:
            chosen = (kind, pts)
    kind, pts = chosen
    p0, pe = pts[0], pts[-1]
    if kind == 0:
        span = pe[0] - p0[0]
        return pe[1] if span == 0 else p0[1] + (pe[1] - p0[1]) * (t - p0[0]) / span
    if kind == 2:
        return p0[1] if t < pe[0] else pe[1]
    if kind == 3:
        return pe[1] if t > p0[0] else p0[1]
    lo, hi = F(0), F(1)
    for _ in range(90):
        mid = (lo + hi) / 2
        if bez(pts[0][0], pts[1][0], pts[2][0], pts[3][0], mid) < t:
            lo = mid
        else:
            hi = mid
    s = (lo + hi) / 2
    return bez(pts[0][1], pts[1][1], pts[2][1], pts[3][1], s)


def cases():
    out = []
    fixed = {
        "linear": [0, 0, 0, 1, 1, 0, 3, -1],
        "stepped": [0, 5, 2, 1, 7, 2, 2, 1],
        "inverse stepped": [0, 5, 3, 1, 7, 3, 2, 1],
        "bezier restricted": [0, 0, 1, 1 / 3, 0.5, 2 / 3, 0.5, 1, 1],
        "bezier skewed": [0, 0, 1, 0.1, 1, 0.2, -1, 1, 0.25],
        "bezier flat time": [0, 1, 1, 0.5, 2, 0.5, 3, 0.5, 0],
        "two beziers": [0, 0, 1, 0.1, 0.2, 0.3, 0.9, 0.5, 1, 1, 0.6, 0.0, 0.7, 0.2, 0.9, 0.1],
        "mixed": [0, 0, 0, 0.5, 1, 2, 0.75, 0.2, 3, 1.0, 0.2, 1, 1.25, 0.9, 1.5, 0.9, 1.75, 0.1, 0, 2, 0.4],
        "single point": [0.5, 3],
        "zero length steps": [0, 0, 2, 0.5, 1, 2, 0.5, 2, 0, 1, 3],
    }
    for name, flat in fixed.items():
        out.append((name, flat))
    rng = random.Random(20261022)
    for k in range(40):
        t = 0.0
        v = rng.uniform(-2, 2)
        flat = [round(t, 4), round(v, 4)]
        for _ in range(rng.randint(1, 6)):
            kind = rng.choice([0, 1, 2, 3])
            n = 3 if kind == 1 else 1
            ts = sorted(round(t + rng.uniform(0, 1.0), 4) for _ in range(n))
            flat.append(kind)
            for tt in ts:
                v = round(rng.uniform(-2, 2), 4)
                flat += [tt, v]
            t = ts[-1]
        out.append(("random %d" % k, flat))
    return out


def sample_times(flat):
    ts = set()
    pts = flat[0::1]
    first, segs = parse(flat)
    times = [first[0]] + [p[0] for _, s in segs for p in s[1:]]
    lo, hi = float(min(times)), float(max(times))
    for t in times:
        ts.add(float(t))
        ts.add(float(t) - 0.001)
        ts.add(float(t) + 0.001)
    ts.add(lo - 1)
    ts.add(hi + 1)
    for i in range(1, 12):
        ts.add(lo + (hi - lo) * i / 12)
    return sorted(ts)


def render():
    lines = ["// Generated by tools/compat/puppet_curves.py; do not edit. Golden values of the motion curve evaluator, computed with exact rational arithmetic.",
             "#pragma once", "", "#include <vector>", "", "namespace puppetgolden {", "",
             "struct Curve {", "    const char *name;", "    std::vector<double> segments;", "    std::vector<double> times;", "    std::vector<double> values;", "};", "",
             "inline const std::vector<Curve> &curves()", "{", "    static const std::vector<Curve> all = {"]
    for name, flat in cases():
        times = sample_times(flat)
        values = [float(value(flat, t)) for t in times]
        lines.append('        {"%s",' % name)
        lines.append("         {%s}," % ", ".join(repr(float(x)) for x in flat))
        lines.append("         {%s}," % ", ".join(repr(t) for t in times))
        lines.append("         {%s}}," % ", ".join(repr(v) for v in values))
    lines += ["    };", "    return all;", "}", "", "} // namespace puppetgolden", ""]
    return "\n".join(lines)


def main():
    ap = argparse.ArgumentParser()
    g = ap.add_mutually_exclusive_group(required=True)
    g.add_argument("--out")
    g.add_argument("--check")
    a = ap.parse_args()
    text = render()
    if a.out:
        with open(a.out, "w") as f:
            f.write(text)
        return 0
    with open(a.check) as f:
        if f.read() != text:
            print("puppet_curves.py: %s is out of date" % a.check, file=sys.stderr)
            return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
